export function getStaticVehicleSketch(templateName?: string | null): Record<string, string> {
  const fallback = VEHICLE_SKETCH_TEMPLATES["Seat Ibiza"];
  if (!templateName) return fallback;
  if (VEHICLE_SKETCH_TEMPLATES[templateName]) return VEHICLE_SKETCH_TEMPLATES[templateName];
  
  const lower = templateName.toLowerCase();
  for (const [key, val] of Object.entries(VEHICLE_SKETCH_TEMPLATES)) {
    if (lower.includes(key.toLowerCase()) || key.toLowerCase().includes(lower)) {
      return val;
    }
  }
  return fallback;
}
